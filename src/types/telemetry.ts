/** Connection status of the hardware node. */
export type ConnectionStatus = "live" | "stale" | "offline";

/** A recommendation generated by the heuristic engine. */
export interface Recommendation {
  id: string;
  severity: "info" | "warning" | "critical";
  sensor: SensorKey;
  message: string;
  icon: string;
}


/**
 * types/telemetry.ts
 * ─────────────────────────────────────────────────────────────────
 * Core data interfaces for the FarmAssist IoT Dashboard.
 *
 * These types model the shapes stored in Firebase Realtime Database by the ESP
 * microcontroller and consumed by the React dashboard.
 *
 * RTDB path: sensor
 * ─────────────────────────────────────────────────────────────────
 */

/** Live sensor telemetry pushed by the ESP microcontroller. */
export interface SensorTelemetry {
  /** Air temperature in °C */
  temperature: number;
  /** Soil moisture in % */
  moisture: number;
  /** Water reservoir level in % */
  waterLevel: number;
  /** Light intensity in lux */
  light: number;
  /** Unix epoch (ms) — generated client-side since RTDB has no timestamp */
  timestamp: number;
}

/** Metadata describing the device sending telemetry. */
export interface DeviceMeta {
  id: string;
  name: string;
  lastSeen: number;
}

/** A single point on the live telemetry chart. */
export interface ChartDataPoint {
  /** Unix timestamp in ms (used as the X axis) */
  timestamp: number;
  /** The metric value for this snapshot */
  value: number;
  /** Individual sensor values for per-sensor chart selection */
  temperature?: number;
  moisture?: number;
  waterLevel?: number;
  light?: number;
}

/**
 * A persisted graph snapshot saved to the `graph_history` collection.
 * Used to retain historical chart data across page refreshes.
 */
export interface GraphSnapshot {
  /** Auto-generated Firestore document ID */
  id: string;
  /** Which sensor metric this snapshot represents */
  metricType: SensorKey;
  /** Ordered array of data points */
  dataPoints: ChartDataPoint[];
  /** Unix epoch (ms) when the snapshot was created */
  createdAt: number;
}

/** Union of all sensor metric keys — used for type-safe lookups. */
export type SensorKey = "temperature" | "moisture" | "waterLevel" | "light";

/** Display metadata for each sensor metric. */
export interface SensorMeta {
  label: string;
  unit: string;
  icon: string; // Lucide icon name
  color: string; // Tailwind color class (for charts)
  hexColor: string; // Raw hex for Recharts stroke
  min: number;
  max: number;
  optimalRange: [number, number];
}

